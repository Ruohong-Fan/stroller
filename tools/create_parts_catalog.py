#!/usr/bin/env python3
"""Export the standalone GLBs and selector data for the parts browser."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from create_cabin_parts import build_cabin_parts
from create_frame_parts import build_frame_parts
from generate_wheel_variants import ROOT


CATEGORIES = (
    ("cabins", "座舱"),
    ("wheels", "轮组"),
    ("crossbars", "横杆"),
    ("beams", "主副梁"),
)


def build_parts_catalog(output):
    by_category = {"cabins": build_cabin_parts(output), **build_frame_parts(output)}
    catalog = []
    for key, name in CATEGORIES:
        parts = by_category[key]
        if not parts or len({part["id"].lower() for part in parts}) != len(parts):
            raise ValueError(f"Part IDs must be present and unique in {key}")
        for part in parts:
            if not (output / (part["path"] + ".glb")).is_file():
                raise ValueError(f"Standalone GLB missing for {part['id']}")
        catalog.append({"id": key, "name": name, "parts": parts})
        print(f"{name} ({key}): {len(parts)} parts")

    data = json.dumps(catalog, ensure_ascii=False, indent=2)
    (output / "other" / "catalog.js").write_text(
        "// Generated by tools/create_parts_catalog.py\n"
        f"const STROLLER_PARTS = {data};\n",
        encoding="utf-8",
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "models")
    build_parts_catalog(parser.parse_args().output)


if __name__ == "__main__":
    main()
